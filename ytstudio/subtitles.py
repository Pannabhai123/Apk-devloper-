#  burn-in
# --------------------------------------------------------------------------- #
def _escape_filter_path(p: str) -> str:
    # FFmpeg filtergraph escaping: backslash, colon, single quote
    return p.replace("\\", "/").replace(":", r"\:").replace("'", r"'\''")


def burn(video: str | Path, subtitle: str | Path, out: str | Path, *,
         style: SubtitleStyle | None = None, width: int = 1920, height: int = 1080,
         fps: int | None = None, crf: int = 18, preset: str = "medium",
         audio_copy: bool = True, font_dir: Path | None = None) -> Path:
    """Burn subtitles into the picture (hard subs - always readable on mobile)."""
    if not has_filter("subtitles"):
        raise RuntimeError("this FFmpeg build has no `subtitles`/libass filter")
    from .tools import fontconfig_env

    exe = ffmpeg()
    video, out = Path(video), Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    sub = Path(subtitle)
    if sub.suffix.lower() == ".ass":
        vf = f"ass='{_escape_filter_path(str(sub.resolve()))}'"
    else:
        st = (style or DEFAULT_STYLE).scaled(width, height)
        force = ",".join([
            f"FontName={st.font}",
            f"FontSize={st.font_size}",
            f"PrimaryColour={st.primary}",
            f"OutlineColour={st.outline_colour}",
            f"BackColour={st.back_colour}",
            "BorderStyle=1",
            f"Outline={st.outline}",
            f"Shadow={st.shadow}",
            f"Alignment={st.alignment}",
            f"MarginV={st.margin_v}",
            f"MarginL={st.margin_l}",
            f"MarginR={st.margin_r}",
            "Bold=1",
        ])
        vf = (f"subtitles='{_escape_filter_path(str(sub.resolve()))}'"
              f":force_style='{force}'")
    cmd = [exe, "-hide_banner", "-loglevel", "error", "-y", "-i", str(video),
           "-vf", vf, "-c:v", "libx264", "-preset", preset, "-crf", str(crf),
           "-pix_fmt", "yuv420p"]
    if fps:
        cmd += ["-r", str(fps)]
    cmd += ["-c:a", "copy"] if audio_copy else ["-c:a", "aac", "-b:a", "320k"]
    cmd += ["-movflags", "+faststart", str(out)]
    run(cmd, timeout=7200, check=True, env=fontconfig_env(font_dir))
    return out


def write_sidecar(cues: list[Cue], out_base: str | Path, *, width=1920, height=1080,
                  style: SubtitleStyle | None = None, srt=True, vtt=True,
                  ass=True) -> dict:
    """Write the subtitle deliverables you upload to YouTube as caption tracks."""
    out_base = Path(out_base)
    out_base.parent.mkdir(parents=True, exist_ok=True)
    paths = {}
    if srt:
        paths["srt"] = write_srt(cues, out_base.with_suffix(".srt"))
    if vtt:
        paths["vtt"] = write_vtt(cues, out_base.with_suffix(".vtt"))
    if ass:
        paths["ass"] = write_ass(cues, out_base.with_suffix(".ass"), width=width,
                                 height=height, style=style)
    return paths
