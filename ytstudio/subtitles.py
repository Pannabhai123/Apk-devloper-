"""Subtitles: SRT/ASS authoring, chunking, styling and libass burn-in."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from .tools import ffmpeg, find_font, has_filter, run

# --------------------------------------------------------------------------- #
#  data model
# --------------------------------------------------------------------------- #
@dataclass
class Cue:
    start: float
    end: float
    text: str

    @property
    def duration(self) -> float:
        return max(0.001, self.end - self.start)


@dataclass
class SubtitleStyle:
    """Everything YouTube auto-captions does not give you: real typography."""
    font: str = "DejaVuSans-Bold"
    font_size: int = 54          # in output pixels (ASS PlayRes = video size)
    primary: str = "&H00FFFFFF"  # ASS colour is &HAABBGGRR
    outline_colour: str = "&H00101010"
    back_colour: str = "&H80000000"
    bold: int = 1
    italic: int = 0
    border_style: int = 1
    outline: int = 3
    shadow: int = 1
    alignment: int = 2           # bottom-centre
    margin_v: int = 70
    margin_l: int = 120
    margin_r: int = 120
    max_chars: int = 88
    max_lines: int = 2
    fade_ms: int = 120
    uppercase: bool = False

    def scaled(self, width: int, height: int) -> "SubtitleStyle":
        """Scale typography to the target resolution (designed at 1080p)."""
        k = height / 1080.0
        s = SubtitleStyle(**self.__dict__)
        s.font_size = int(round(self.font_size * k))
        s.outline = max(1, int(round(self.outline * k)))
        s.shadow = max(0, int(round(self.shadow * k)))
        s.margin_v = int(round(self.margin_v * k))
        s.margin_l = int(round(self.margin_l * (width / 1920.0)))
        s.margin_r = int(round(self.margin_r * (width / 1920.0)))
        return s


DEFAULT_STYLE = SubtitleStyle()


# --------------------------------------------------------------------------- #
#  writers
# --------------------------------------------------------------------------- #
def _srt_time(t: float) -> str:
    t = max(0.0, t)
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = int(t % 60)
    ms = int(round((t - int(t)) * 1000))
    if ms == 1000:
        s, ms = s + 1, 0
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def _ass_time(t: float) -> str:
    t = max(0.0, t)
    h = int(t // 3600)
    m = int((t % 3600) // 60)
    s = t % 60
    return f"{h:d}:{m:02d}:{s:05.2f}"


def write_srt(cues: list[Cue], path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = []
    for i, c in enumerate(cues, 1):
        lines.append(f"{i}\n{_srt_time(c.start)} --> {_srt_time(c.end)}\n{c.text.strip()}\n")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_vtt(cues: list[Cue], path: str | Path) -> Path:
    path = Path(path)
    lines = ["WEBVTT\n"]
    for c in cues:
        st = _srt_time(c.start).replace(",", ".")
        en = _srt_time(c.end).replace(",", ".")
        lines.append(f"{st} --> {en}\n{c.text.strip()}\n")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_ass(cues: list[Cue], path: str | Path, *, width: int = 1920, height: int = 1080,
              style: SubtitleStyle | None = None, title: str = "ytstudio") -> Path:
    """ASS gives pixel-accurate placement, real fonts, shadows and fades."""
    style = (style or DEFAULT_STYLE).scaled(width, height)
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    header = f"""[Script Info]
; Generated by ytstudio
Title: {title}
ScriptType: v4.00+
PlayResX: {width}
PlayResY: {height}
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Default,{style.font},{style.font_size},{style.primary},&H000000FF,{style.outline_colour},{style.back_colour},{style.bold},{style.italic},0,0,100,100,0,0,{style.border_style},{style.outline},{style.shadow},{style.alignment},{style.margin_l},{style.margin_r},{style.margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    events = []
    for c in cues:
        text = c.text.strip().replace("\n", r"\N")
        if style.uppercase:
            text = text.upper()
        fade = rf"{{\fad({style.fade_ms},{style.fade_ms})}}" if style.fade_ms else ""
        events.append(
            f"Dialogue: 0,{_ass_time(c.start)},{_ass_time(c.end)},Default,,0,0,0,,{fade}{text}"
        )
    path.write_text(header + "\n".join(events) + "\n", encoding="utf-8")
    return path


# --------------------------------------------------------------------------- #
#  readers
# --------------------------------------------------------------------------- #
_TIME_RE = re.compile(
    r"(?P<h>\d{1,2}):(?P<m>\d{2}):(?P<s>\d{2})[.,](?P<ms>\d{1,3})\s*-->\s*"
    r"(?P<h2>\d{1,2}):(?P<m2>\d{2}):(?P<s2>\d{2})[.,](?P<ms2>\d{1,3})"
)


def _secs(h, m, s, ms) -> float:
    return int(h) * 3600 + int(m) * 60 + int(s) + int(ms.ljust(3, "0")) / 1000.0


def read_srt(path: str | Path) -> list[Cue]:
    """Tolerant SRT/VTT reader (handles BOM, CRLF, missing indices)."""
    raw = Path(path).read_text(encoding="utf-8-sig", errors="replace").replace("\r\n", "\n")
    cues: list[Cue] = []
    for block in re.split(r"\n{2,}", raw):
        lines = [l for l in block.split("\n") if l.strip() != ""]
        if not lines:
            continue
        if lines[0].strip().upper().startswith("WEBVTT"):
            lines = lines[1:]
            if not lines:
                continue
        idx = 0
        if not _TIME_RE.search(lines[0]) and len(lines) > 1 and _TIME_RE.search(lines[1]):
            idx = 1
        if idx >= len(lines):
            continue
        m = _TIME_RE.search(lines[idx])
        if not m:
            continue
        text = "\n".join(lines[idx + 1:]).strip()
        text = re.sub(r"<[^>]+>", "", text)  # strip inline tags
        cues.append(Cue(_secs(m["h"], m["m"], m["s"], m["ms"]),
                        _secs(m["h2"], m["m2"], m["s2"], m["ms2"]), text))
    cues.sort(key=lambda c: c.start)
    return cues


# --------------------------------------------------------------------------- #
#  generating cues: (a) from a known transcript, (b) proportional to text
# --------------------------------------------------------------------------- #
def cues_from_text(text: str, start: float, duration: float, *,
                   max_chars: int = 88, min_duration: float = 1.1,
                   max_duration: float = 7.0, gap: float = 0.06) -> list[Cue]:
    """Distribute a block of narration across `duration`, weighted by chunk length."""
    from .audio import split_script

    chunks = split_script(text, max_chars=max_chars)
    if not chunks:
        return []
    weights = [max(1, len(c)) for c in chunks]
    total = sum(weights)
    usable = max(0.5, duration - gap * (len(chunks) - 1))
    units = [usable * w / total for w in weights]
    # clamp durations, then re-normalise so we exactly fill the window
    units = [min(max(u, min_duration), max_duration) for u in units]
    scale = usable / sum(units)
    units = [u * scale for u in units]
    cues: list[Cue] = []
    t = start
    for chunk, dur in zip(chunks, units):
        cues.append(Cue(round(t, 3), round(t + dur, 3), chunk))
        t += dur + gap
    return cues


def cues_from_script(sections: list[dict], *, max_chars: int = 88) -> list[Cue]:
    """sections = [{'text':..., 'start':..., 'duration':...}, ...]"""
    out: list[Cue] = []
    for s in sections:
        out.extend(cues_from_text(s["text"], s.get("start", 0.0), s["duration"],
                                 max_chars=max_chars))
    return out


def transcribe(*args, **kwargs):
    """Automatic transcription hook.

    The sandbox used to build this system has no access to model hubs, so no
    local ASR model is bundled. Install `faster-whisper` (or `openai-whisper`)
    and this function will use it. It deliberately raises a clear error instead
    of silently returning fake timings.
    """
    try:
        from faster_whisper import WhisperModel  # type: ignore
    except Exception as exc:  # pragma: no cover
        raise RuntimeError(
            "Automatic transcription unavailable: `faster-whisper` is not installed or "
            "its model could not be downloaded (huggingface.co is not reachable from this "
            "sandbox). Provide an SRT/VTT, or run transcription on a machine with model access."
        ) from exc
    audio_path = kwargs.get("audio") or (args[0] if args else None)
    model_size = kwargs.get("model", "small")
    language = kwargs.get("language", None)
    model = WhisperModel(model_size, device="cpu", compute_type="int8")
    segments, _info = model.transcribe(str(audio_path), language=language, vad_filter=True)
    cues = [Cue(s.start, s.end, s.text.strip()) for s in segments if s.text.strip()]
    if kwargs.get("out"):
        write_srt(cues, kwargs["out"])
    return cues


